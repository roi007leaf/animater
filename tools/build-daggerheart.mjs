// Daggerheart library source: domain cards and weapons from the installed `daggerheart` system's
// compendia, written to data/daggerheart-catalog.mjs (committed). Conditions are not compendium
// documents (CONFIG.DH.GENERAL conditions), so the tool only checks their ids still exist in the
// system bundle.
//
//   node tools/build-daggerheart.mjs [--reader=leveldb|github] [--system=<path>] [--foundry=<app path>]
//
// leveldb (default): reads the installed packs offline through Foundry's own classic-level module,
//   from a temp copy of each pack so a running world's LOCK is never touched.
// github: the same documents from Foundryborne/daggerheart's src/packs JSON at the installed
//   version's tag, cached under .cache/daggerheart-source/<sha>/ (how the PF2e/SF2e tools read sources).
//   Used automatically when the LevelDB reader is unavailable.
// The reader used is recorded as DAGGERHEART_SOURCE.reader.
import { cpSync, existsSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
export const OUTPUT = join(ROOT, "data", "daggerheart-catalog.mjs");
const DEFAULT_SYSTEM = resolve(ROOT, "..", "..", "systems", "daggerheart");
const DEFAULT_FOUNDRY = process.platform === "win32" ? "C:/Program Files/Foundry Virtual Tabletop/resources/app" : "/opt/foundryvtt/resources/app";
const REPOSITORY = "Foundryborne/daggerheart";
export const PACKS = Object.freeze({
  card: { name: "domains", path: "packs/domains", source: "src/packs/domains", type: "domainCard" },
  weapon: { name: "weapons", path: "packs/items/weapons", source: "src/packs/items/weapons", type: "weapon" },
});
export const CONDITION_IDS = Object.freeze(["vulnerable", "hidden", "restrained", "deathMove", "defeated", "unconscious", "dead"]);
const RANGES = new Set(["melee", "veryClose", "close", "far", "veryFar"]);
const CARD_TYPES = new Set(["ability", "spell", "grimoire"]);

const text = (value) => (typeof value === "string" ? value : "");
const list = (value) => (Array.isArray(value) ? value : []);

export function cardRow(doc) {
  const s = doc?.system ?? {};
  return {
    id: text(doc?._id), name: text(doc?.name), img: text(doc?.img), domain: text(s.domain).toLowerCase(),
    level: Number(s.level) || 0, cardType: text(s.type) || "ability", recallCost: Number(s.recallCost) || 0,
    actions: Object.values(s.actions ?? {}).map((a) => ({ type: text(a?.type), roll: a?.roll?.type ?? null, target: a?.target?.type ?? null })),
  };
}

export function weaponRow(doc) {
  const s = doc?.system ?? {}, attack = s.attack ?? {};
  return {
    id: text(doc?._id), name: text(doc?.name), img: text(doc?.img), tier: Number(s.tier) || 1,
    range: text(attack.range), trait: attack.roll?.trait ?? null, damageTypes: list(attack.damage?.main?.type).map(String), burden: text(s.burden),
  };
}

// CONFIG.DH.GENERAL conditions and defeatedConditionChoices: `id: 'x', name: 'DAGGERHEART.CONFIG.Condition.x.name'`.
export function conditionIdsFrom(bundle) {
  const ids = [...String(bundle).matchAll(/id: '(\w+)',\s*name: 'DAGGERHEART\.CONFIG\.Condition\.\1\.name'/g)].map((m) => m[1]);
  return [...new Set(ids)];
}

export function validateRows({ cards = [], weapons = [] } = {}) {
  const problems = [], id = (row) => /^[A-Za-z0-9]{16}$/.test(row.id);
  for (const c of cards) {
    if (!id(c)) problems.push(`card id ${JSON.stringify(c.id)}`);
    if (!c.name) problems.push(`card ${c.id}: no name`);
    if (!c.domain) problems.push(`${c.name}: no domain`);
    if (!(c.level >= 1 && c.level <= 10)) problems.push(`${c.name}: level ${c.level}`);
    if (!CARD_TYPES.has(c.cardType)) problems.push(`${c.name}: card type ${c.cardType}`);
  }
  for (const w of weapons) {
    if (!id(w)) problems.push(`weapon id ${JSON.stringify(w.id)}`);
    if (!w.name) problems.push(`weapon ${w.id}: no name`);
    if (!RANGES.has(w.range)) problems.push(`${w.name}: range ${JSON.stringify(w.range)}`);
    if (!w.damageTypes.length) problems.push(`${w.name}: no damage type`);
  }
  return problems;
}

export function renderModule({ source, cards, weapons }) {
  const json = (value) => JSON.stringify(value);
  return [
    "// Generated by tools/build-daggerheart.mjs from the Daggerheart system's compendia. Do not edit by hand.",
    `export const DAGGERHEART_SOURCE = ${json(source)};`,
    `export const DAGGERHEART_CARDS = [\n${cards.map(json).join(",\n")}\n];`,
    `export const DAGGERHEART_WEAPONS = [\n${weapons.map(json).join(",\n")}\n];`,
    "",
  ].join("\n");
}

export async function readLevelDb(systemDir, foundryApp) {
  const require = createRequire(join(foundryApp, "package.json"));
  const { ClassicLevel } = require("classic-level");
  const out = {};
  for (const [kind, pack] of Object.entries(PACKS)) {
    const copy = mkdtempSync(join(tmpdir(), "animater-daggerheart-"));
    try {
      cpSync(join(systemDir, pack.path), copy, { recursive: true });
      rmSync(join(copy, "LOCK"), { force: true });
      const db = new ClassicLevel(copy, { valueEncoding: "json" }), docs = [];
      for await (const [key, value] of db.iterator()) if (key.startsWith("!items!") && value?.type === pack.type) docs.push(value);
      await db.close();
      out[kind] = docs;
    } finally {
      rmSync(copy, { recursive: true, force: true });
    }
  }
  return out;
}

async function fetchJSON(url) {
  const response = await fetch(url, { headers: { "User-Agent": "Animater-catalog",
    ...(process.env.GITHUB_TOKEN && url.startsWith("https://api.github.com/") ? { Authorization: `Bearer ${process.env.GITHUB_TOKEN}` } : {}) } });
  if (!response.ok) throw Error(`${response.status}: ${url}`);
  return response.json();
}

export async function readGithub(version) {
  const tree = await fetchJSON(`https://api.github.com/repos/${REPOSITORY}/git/trees/${version}?recursive=1`);
  if (tree.truncated) throw Error("Daggerheart source tree truncated; cannot assert complete coverage.");
  const cache = join(ROOT, ".cache", "daggerheart-source", tree.sha);
  mkdirSync(cache, { recursive: true });
  const docs = {};
  for (const [kind, pack] of Object.entries(PACKS)) {
    const files = tree.tree.filter((e) => e.type === "blob" && e.path.startsWith(`${pack.source}/`) && e.path.endsWith(".json") && !e.path.split("/").pop().startsWith("folders_"));
    const found = [];
    let cursor = 0;
    await Promise.all(Array.from({ length: 12 }, async () => {
      while (cursor < files.length) {
        const entry = files[cursor++], file = join(cache, `${entry.sha}.json`);
        let doc;
        try { doc = JSON.parse(readFileSync(file, "utf8")); }
        catch { doc = await fetchJSON(`https://raw.githubusercontent.com/${REPOSITORY}/${tree.sha}/${entry.path}`); writeFileSync(file, JSON.stringify(doc)); }
        if (doc?.type === pack.type) found.push(doc);
      }
    }));
    docs[kind] = found;
  }
  return { docs, sha: tree.sha };
}

export async function build({ reader = "leveldb", systemDir = DEFAULT_SYSTEM, foundryApp = DEFAULT_FOUNDRY, output = OUTPUT } = {}) {
  const version = JSON.parse(readFileSync(join(systemDir, "system.json"), "utf8")).version;
  let docs = null, sha = null, used = reader;
  if (reader === "leveldb") {
    try { docs = await readLevelDb(systemDir, foundryApp); }
    catch (error) { console.warn(`LevelDB reader unavailable (${error.message}); reading ${REPOSITORY} at ${version} instead.`); used = "github"; }
  }
  if (used === "github") ({ docs, sha } = await readGithub(version));
  const byName = (a, b) => a.name.localeCompare(b.name) || a.id.localeCompare(b.id);
  const cards = docs.card.map(cardRow).sort(byName), weapons = docs.weapon.map(weaponRow).sort(byName);
  const problems = validateRows({ cards, weapons });
  if (problems.length) throw Error(`Daggerheart library rows are invalid:\n${problems.join("\n")}`);
  const bundle = join(systemDir, "build", "daggerheart.js");
  const found = existsSync(bundle) ? conditionIdsFrom(readFileSync(bundle, "utf8")) : null;
  const missing = found ? CONDITION_IDS.filter((id) => !found.includes(id)) : [];
  if (missing.length) throw Error(`Daggerheart conditions missing from build/daggerheart.js: ${missing.join(", ")}`);
  const source = { systemId: "daggerheart", version, reader: used, repository: REPOSITORY, ...(sha ? { sha } : {}),
    packs: { card: PACKS.card.name, weapon: PACKS.weapon.name }, counts: { card: cards.length, weapon: weapons.length },
    conditions: [...CONDITION_IDS], conditionsVerified: Boolean(found) };
  writeFileSync(output, renderModule({ source, cards, weapons }));
  return source;
}

if (import.meta.url === pathToFileURL(resolve(process.argv[1] ?? "")).href) {
  const arg = (name) => process.argv.find((a) => a.startsWith(`--${name}=`))?.split("=").slice(1).join("=");
  try {
    const source = await build({ reader: arg("reader") ?? "leveldb", systemDir: arg("system") ?? DEFAULT_SYSTEM, foundryApp: arg("foundry") ?? process.env.FOUNDRY_APP ?? DEFAULT_FOUNDRY });
    console.log(JSON.stringify(source));
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
